function shQuote(value) {
  return `'${String(value).replaceAll("'", "'\\''")}'`;
}

/**
 * Batch expands %NAME% sequences, so a literal percent in an absolute path
 * has to be doubled.
 */
function batchEscape(value) {
  return String(value).replaceAll('%', '%%');
}

export function wrapperFileName(platform = process.platform) {
  return platform === 'win32' ? 'run-host.cmd' : 'run-host.sh';
}

/**
 * Chrome starts a native messaging host through cmd.exe on Windows when the
 * target is not a .exe, so a small .cmd wrapper is enough to launch Node.
 */
export function wrapperContent({
  platform = process.platform,
  nodePath,
  hostScript,
}) {
  if (platform === 'win32') {
    return [
      '@echo off',
      'rem Generated by the Chrome Presence installer.',
      'rem Run the installer again after updating Node.js.',
      `"${batchEscape(nodePath)}" "${batchEscape(hostScript)}" %*`,
      '',
    ].join('\r\n');
  }

  return [
    '#!/bin/sh',
    `exec ${shQuote(nodePath)} ${shQuote(hostScript)} "$@"`,
    '',
  ].join('\n');
}
